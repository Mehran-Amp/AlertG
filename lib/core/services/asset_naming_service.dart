  /// Resolves the full English name for display on the alert card directly beneath the symbol.
  /// Example:
  ///   'ZTS' -> 'Zoetis'
  ///   '1810.HK' -> 'Xiaomi Corporation'
  ///   'NVDA' -> 'NVIDIA Corporation'
  ///   'US13W' -> 'US 13-Week Treasury Yield'
  ///   '9988.HK' -> 'Alibaba Group Holding'
  ///   'SOL' -> 'Solana'
  ///   'USD / JPY' -> 'U.S. dollar / Japanese yen'
  ///   'EUR / USD' -> 'Euro / U.S. dollar'
  static String resolveFullName(
    String symbol, {
    String? baseCurrency,
    String? counterCurrency,
  }) {
    final clean = _normalizeSymbol(symbol.isNotEmpty ? symbol : (baseCurrency ?? ''));
    if (clean.isEmpty) return '';

    final baseClean = _normalizeSymbol(baseCurrency ?? (clean.contains('/') ? clean.split('/').first : ''));
    final quoteClean = _normalizeSymbol(counterCurrency ?? (clean.contains('/') ? clean.split('/').last : ''));

    // 1. Forex Currency Pair: Both base & counter are fiat currencies (e.g. USD / JPY -> "U.S. dollar / Japanese yen")
    if (baseClean.isNotEmpty && quoteClean.isNotEmpty &&
        _forexCurrencies.containsKey(baseClean) &&
        _forexCurrencies.containsKey(quoteClean)) {
      return '${_forexCurrencies[baseClean]} / ${_forexCurrencies[quoteClean]}';
    }

    // 2. Direct Forex ticker with slash or 6-letter (e.g. "USD/JPY" or "EURUSD=X" -> "Euro / U.S. dollar")
    if (clean.contains('/')) {
      final parts = clean.split('/');
      final b = _normalizeSymbol(parts.first);
      final q = _normalizeSymbol(parts.last);
      if (_forexCurrencies.containsKey(b) && _forexCurrencies.containsKey(q)) {
        return '${_forexCurrencies[b]} / ${_forexCurrencies[q]}';
      }
    }
    final strippedForex = clean.endsWith('=X') ? clean.substring(0, clean.length - 2) : clean;
    if (strippedForex.length == 6) {
      final fBase = strippedForex.substring(0, 3);
      final fQuote = strippedForex.substring(3, 6);
      if (_forexCurrencies.containsKey(fBase) && _forexCurrencies.containsKey(fQuote)) {
        return '${_forexCurrencies[fBase]} / ${_forexCurrencies[fQuote]}';
      }
    }

    // 3. Direct match in local/synced catalog cache
    final cached = _findInCatalogSync(clean);
    if (cached != null && cached.isNotEmpty) return cached;

    // 4. Direct match in comprehensive built-in dictionary
    if (_builtinNames.containsKey(clean)) {
      return _builtinNames[clean]!;
    }

    // 5. Fallback without exchange or market suffix (e.g. '1810' for '1810.HK', 'BRK-B' for 'BRK.B')
    if (clean.contains('.')) {
      final withoutSuffix = clean.split('.').first;
      if (_builtinNames.containsKey(withoutSuffix)) {
        return _builtinNames[withoutSuffix]!;
      }
    }

    // 6. Base currency fallback if separate
    if (baseCurrency != null && baseCurrency.isNotEmpty) {
      final cleanBase = _normalizeSymbol(baseCurrency);
      if (_builtinNames.containsKey(cleanBase)) {
        return _builtinNames[cleanBase]!;
      }
    }

    return clean;
  }

  /// Resolves the authentic, exact spoken name for Text-to-Speech (TTS).
  /// Guarantees exact pronunciation for key stocks, HK equities, US yields, crypto & forex.
  static String resolveTtsSpokenName(
    String symbol, {
    String? baseCurrency,
    String? counterCurrency,
  }) {
    final baseClean = _normalizeSymbol(baseCurrency ?? (symbol.contains('/') ? symbol.split('/').first : symbol));
    final quoteClean = _normalizeSymbol(counterCurrency ?? (symbol.contains('/') ? symbol.split('/').last : ''));

    // 1. Forex vocal pronunciation: "U.S. dollar Japanese yen"
    if (baseClean.isNotEmpty && quoteClean.isNotEmpty &&
        _forexCurrencies.containsKey(baseClean) &&
        _forexCurrencies.containsKey(quoteClean)) {
      return '${_forexCurrencies[baseClean]} ${_forexCurrencies[quoteClean]}';
    }

    final strippedForex = symbol.trim().toUpperCase().replaceAll(' ', '');
    final cleanStripped = strippedForex.endsWith('=X') ? strippedForex.substring(0, strippedForex.length - 2) : strippedForex;
    if (cleanStripped.length == 6) {
      final fBase = cleanStripped.substring(0, 3);
      final fQuote = cleanStripped.substring(3, 6);
      if (_forexCurrencies.containsKey(fBase) && _forexCurrencies.containsKey(fQuote)) {
        return '${_forexCurrencies[fBase]} ${_forexCurrencies[fQuote]}';
      }
    }

    final name = resolveFullName(symbol, baseCurrency: baseCurrency, counterCurrency: counterCurrency);

    // Exact names requested
    if (name.contains('Xiaomi')) return 'Xiaomi Corporation';
    if (name.contains('Alibaba')) return 'Alibaba Group Holding';
    if (name.contains('NVIDIA') || name.contains('Nvidia')) return 'NVIDIA Corporation';
    if (name.contains('Zoetis')) return 'Zoetis';
    if (name.contains('13-Week') || symbol.toUpperCase().contains('US13W') || symbol.toUpperCase().contains('^IRX')) {
      return 'US 13-Week Treasury Yield';
    }
    if (name.contains('Solana') || symbol.toUpperCase() == 'SOL') return 'Solana';

    // For all other assets, remove bracketed clarifications like "(Google)" or parenthetical notes
    var spoken = name
        .replaceAll(' Limited', '')
        .replaceAll(RegExp(r'\s*\([^)]*\)'), '')
        .trim();

    return spoken.isNotEmpty ? spoken : name;
  }

  /// True if this asset is a percentage bond yield (e.g. US13W, US10Y)
  static bool isYieldAsset(String symbol) {
    final clean = _normalizeSymbol(symbol);
    return _yieldSymbols.contains(clean);
  }

  /// True if this asset is an index evaluated in points (e.g. S&P 500, VIX)
  static bool isIndexAsset(String symbol) {
    final clean = _normalizeSymbol(symbol);
    return _indexSymbols.contains(clean);
  }

  static String _normalizeSymbol(String s) {
    return s.trim().toUpperCase().replaceAll(' ', '');
  }

  static String? _findInCatalogSync(String sym) {
    try {
      final items = CatalogSyncService.instance.items;
      for (final item in items) {
        if (item.symbol.toUpperCase() == sym && item.nameEn.isNotEmpty) {
          return item.nameEn;
        }
      }
    } catch (_) {}
    return null;
  }
